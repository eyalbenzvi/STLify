/** Every vertex and index of every part, in build order. */
async function rebuildFingerprint(document: DesignDocument): Promise<string> {
  const result = await buildDocument(document, { useLayerCache: false });
  expect(result.status).toBe("ok");
  expect(result.parts.length).toBe(1);
  return result.parts
    .map((part) => {
      const mesh = part.worldMesh;
      const positions = Array.from(mesh.positions, (v) => v.toFixed(6)).join(",");
      const indices = Array.from(mesh.indices).join(",");
      return `${positions}|${indices}`;
    })
    .join("||");
}

function savedWith(settings: Record<string, unknown>): string {
  const clone = structuredClone(SAVED_DESIGN);
  Object.assign(clone.document.layers[0].settings, settings);
  return JSON.stringify(clone);
}

describe("a design saved before V7 rebuilds unchanged", () => {
  it("builds the stored contours, hole included", async () => {
    const { document, warningsHe } = importDesignFile(JSON.stringify(SAVED_DESIGN));
    expect(warningsHe).toEqual([]);
    const result = await buildDocument(document, { useLayerCache: false });
    expect(result.status).toBe("ok");
    const part = result.parts[0];
    expect(part.stats.watertight).toBe(true);
    // Ring of r=20 minus r=8, extruded 4 mm, as 24/16-gons.
    const outer = (24 / 2) * 20 * 20 * Math.sin((2 * Math.PI) / 24);
    const inner = (16 / 2) * 8 * 8 * Math.sin((2 * Math.PI) / 16);
    expect(part.stats.volumeMm3).toBeCloseTo((outer - inner) * 4, 2);
  }, 60_000);

  it("ignores the stored silhouette threshold — nothing re-thresholds on load", async () => {
    // If a rebuild ever re-derived the threshold (or consulted the stored
    // one), these three files would build to three different shapes.
    const base = await rebuildFingerprint(
      importDesignFile(JSON.stringify(SAVED_DESIGN)).document
    );
    for (const threshold of [0.05, 0.93]) {
      const other = await rebuildFingerprint(importDesignFile(savedWith({ threshold })).document);
      expect(other).toBe(base);
    }
  }, 120_000);

  it("ignores the stored resolution, smoothing level and invert flag too", async () => {
    const base = await rebuildFingerprint(
      importDesignFile(JSON.stringify(SAVED_DESIGN)).document
    );
    const other = await rebuildFingerprint(
      importDesignFile(savedWith({ resolution: 512, smoothingLevel: 5, invert: true })).document
    );
    expect(other).toBe(base);
  }, 120_000);
});
